def _parse_rows(rows: tuple[str, ...]) -> tuple[int, ...]:
    """把 ``#/.`` 字符串行解析为位图行（每位代表一个像素）。"""
    parsed: list[int] = []
    for row in rows:
        if len(row) != GLYPH_WIDTH:
            raise ValueError(f"内置字体行宽必须为 {GLYPH_WIDTH}：{row!r}")
        value = 0
        for char in row:
            value = (value << 1) | (1 if char == "#" else 0)
        parsed.append(value)
    return tuple(parsed)


#: 码点 -> 7 个位图行（每行低 5 位有效）
GLYPHS: dict[int, tuple[int, ...]] = {
    codepoint: _parse_rows(rows) for codepoint, rows in _RAW_GLYPHS.items()
}


def supports(codepoint: int) -> bool:
    """该码点是否由内置点阵字体覆盖。"""
    return codepoint in GLYPHS


def glyph_rows(codepoint: int) -> tuple[int, ...] | None:
    """返回字形的 7 个位图行；未覆盖返回 ``None``。"""
    return GLYPHS.get(codepoint)
