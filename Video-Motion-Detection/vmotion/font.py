#: 不认识的字符画成全点亮块
_FALLBACK = (0x7F, 0x7F, 0x7F, 0x7F, 0x7F)


def _glyph(ch):
    """取字符字形列数据；小写转大写，超范围用占位块。"""
    if "a" <= ch <= "z":
        ch = chr(ord(ch) - 32)
    return _FONT.get(ch, _FALLBACK)


def text_width(text):
    """字符串渲染宽度（像素）：每字 6 像素步进，末字不留右间距。"""
    if not text:
        return 0
    return len(text) * GLYPH_ADVANCE - 1


def render_text_mask(text):
    """把文字栅格化为 ``(宽, 高, bytes)`` 掩码，打点处字节为 1。

    掩码尺寸紧凑包裹文字，渲染侧把 1 处替换为前景色即可；
    可选再用掩码做描边/底色。
    """
    width = text_width(text)
    if width <= 0:
        return 0, GLYPH_H, b""
    mask = bytearray(width * GLYPH_H)
    for i, ch in enumerate(text):
        cols = _glyph(ch)
        x0 = i * GLYPH_ADVANCE
        for cx, col_bits in enumerate(cols):
            for row in range(GLYPH_H):
                if col_bits & (1 << row):
                    mask[row * width + x0 + cx] = 1
    return width, GLYPH_H, bytes(mask)
